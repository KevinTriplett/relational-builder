/**
 * Export Relational Builder's principles and practices as plain markdown
 * under public/knowledge/, served at https://relationalbuilder.org/knowledge/
 * so the RT MCP server (github.com/The-Relational-Technology-Project/
 * rt-mcp-server) can hand them to any AI tool a builder works in.
 *
 * Runs as `prebuild` (every deploy regenerates them) and on demand:
 *   node scripts/export-builder-knowledge.mjs
 *
 * The sources of truth stay in src/knowledge/ (TypeScript, with the app's
 * extensionless imports), so this bundles a tiny entry with esbuild-wasm (already a dependency) and
 * evaluates it — the same way Vite would — instead of teaching Node the
 * app's module conventions.
 */
import { build } from 'esbuild-wasm';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const outDir = join(root, 'public', 'knowledge');

const bundled = await build({
  stdin: {
    contents: [
      "export { formatPrinciplesForPrompt } from './src/knowledge/rtp-principles';",
      "export { FRAMES } from './src/knowledge/frames';",
      "export { BUILDER_PRACTICE_MD } from './src/knowledge/builder-practice';",
    ].join('\n'),
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  platform: 'node',
  format: 'esm',
  write: false,
  logLevel: 'silent',
});
const code = bundled.outputFiles[0].text;
const { formatPrinciplesForPrompt, FRAMES, BUILDER_PRACTICE_MD } = await import(
  `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`
);

mkdirSync(outDir, { recursive: true });

const stamp =
  '<!-- Generated by scripts/export-builder-knowledge.mjs from src/knowledge/ — edit the sources, not this file. -->\n\n';

const principles =
  stamp +
  '# Relational Technology Principles, as Relational Builder carries them\n\n' +
  'This is the block every Relational Builder conversation begins with. Give it to your own AI as a system prompt or a first message and it builds from the same ground.\n\n' +
  formatPrinciplesForPrompt() +
  '\n';

const frameList = Object.values(FRAMES);
const frames =
  stamp +
  '# Domain frames\n\n' +
  'Frames are principle sets that layer onto the base principles when a project has a particular shape. Relational Builder senses them from what a builder asks for and from which commons entries the request draws on. With your own AI, pick the frame that fits and add it after the principles.\n\n' +
  frameList.map(f => `<!-- frame: ${f.slug} -->\n${f.principles}\n`).join('\n') +
  '\n';

const practice = stamp + BUILDER_PRACTICE_MD;

const index = {
  generated_at: new Date().toISOString(),
  documents: [
    { slug: 'builder-principles', path: '/knowledge/builder-principles.md', title: 'Relational Technology Principles, as Relational Builder carries them' },
    { slug: 'builder-practice', path: '/knowledge/builder-practice.md', title: 'How Relational Builder builds' },
    { slug: 'builder-frames', path: '/knowledge/builder-frames.md', title: 'Domain frames', frames: frameList.map(f => ({ slug: f.slug, label: f.label })) },
  ],
};

writeFileSync(join(outDir, 'builder-principles.md'), principles);
writeFileSync(join(outDir, 'builder-frames.md'), frames);
writeFileSync(join(outDir, 'builder-practice.md'), practice);
writeFileSync(join(outDir, 'index.json'), JSON.stringify(index, null, 2) + '\n');
console.log(`knowledge: wrote ${index.documents.length} documents to public/knowledge/`);
